/* ===========================================================================
 * tools/inject-config.mjs - Phase B (Vercel) build-time config injector.
 * Vercel build command:  node tools/inject-config.mjs
 *
 * WHAT IT DOES
 *   1. Reads Vercel env: SL_SB_URL, SL_SB_KEY, SL_OWNER_EMAILS (comma list).
 *   2. Writes assets/config.generated.js - a build artifact, git-ignored.
 *   3. Idempotently injects  <script src="./assets/config.generated.js">
 *      immediately after the opening <head> of the 5 POS entry points, so a
 *      re-deploy never duplicates the tag.
 *   4. Copies tools/vercel.json to the deploy root as vercel.json, because Vercel
 *      only reads a config file at the root of the deployment while this repo
 *      keeps the source of truth under tools/ (see MASTER_PLAN section 2).
 *
 * WHY A CLASSIC SCRIPT, NOT type="module"
 *   Every app script in the pages is <script type="module">, which is deferred:
 *   it runs only after the document is parsed, and modules execute in document
 *   order - assets/config.js would already have evaluated its priority chain
 *   before a module could set the global. A CLASSIC script in <head> executes
 *   synchronously during parsing, before any deferred module, so window.SL_CONFIG
 *   is guaranteed to exist when assets/config.js reads it. That ordering is the
 *   whole reason the generated file is classic.
 *
 * WHY THE GENERATED FILE IS GIT-IGNORED
 *   It embeds the live Supabase URL and the live PUBLISHABLE key for THIS deploy
 *   - environment truth, not source. .gitignore lists
 *   assets/config.generated.js, so nothing deploy-specific is ever committed and
 *   the committed assets/config.js keeps only placeholder defaults.
 *
 * SERVICE-ROLE KEY NEVER ENTERS THIS PIPELINE
 *   Only the PUBLISHABLE key (sb_publishable_...) may reach the browser. A value
 *   shaped like a Supabase secret key (sk_...) or carrying a service-role marker
 *   aborts the build. The service-role key stays in Supabase tooling (Dashboard,
 *   Edge-Function cron) and never appears in a page, the repo, or a build artifact.
 *
 * FAIL-LOUD: missing env or a secret-shaped key exits non-zero, so the Vercel
 *   build breaks instead of silently shipping placeholder config live.
 * =========================================================================== */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const ENTRY_POINTS = ['index.html', 'menu.html', 'cashier.html', 'kitchen.html', 'owner.html'];
const GENERATED_REL = path.join('assets', 'config.generated.js');
const TAG = '<script src="./assets/config.generated.js"></script>';

const SECRET_KEY_SHAPE = /sk_[a-z0-9_-]{20,}/i;
const SERVICE_ROLE_MARKER = /service[\s_-]*role|service_role/i;

function fail(reason) {
  console.error('inject-config: BUILD FAILED - ' + reason);
  process.exit(1);
}

const sbUrl = String(process.env.SL_SB_URL || '').trim().replace(/\/+$/, '');
const sbKey = String(process.env.SL_SB_KEY || '').trim();
const ownerEmails = String(process.env.SL_OWNER_EMAILS || '')
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean)
  .join(',');

if (sbUrl === '') fail('SL_SB_URL is unset in the Vercel env; refusing to ship the committed placeholder URL. Set SL_SB_URL=https://<project>.supabase.co');
if (sbKey === '') fail('SL_SB_KEY is unset in the Vercel env; refusing to ship an empty key. Set SL_SB_KEY to the PUBLISHABLE key (sb_publishable_...)');
if (SECRET_KEY_SHAPE.test(sbKey)) fail('SL_SB_KEY matches the Supabase SECRET key shape (sk_...); only the PUBLISHABLE key may reach the browser. Use sb_publishable_...');
if (SERVICE_ROLE_MARKER.test(sbKey)) fail('SL_SB_KEY carries a service-role marker; the service-role key must never enter the browser, the repo, or a build artifact.');
if (!/^https:\/\//i.test(sbUrl)) fail('SL_SB_URL must be an https:// Supabase URL (got: ' + sbUrl + ')');
if (!/sb_publishable_/i.test(sbKey)) console.log('inject-config: NOTE - SL_SB_KEY is not sb_publishable_-prefixed; verify it is the publishable (client) key, not a secret.');

const generated =
  '/* GENERATED by tools/inject-config.mjs at Vercel build time - DO NOT EDIT, DO NOT COMMIT.\n' +
  ' * Classic script on purpose: it runs synchronously during <head> parsing, before the\n' +
  ' * deferred type="module" app scripts, so window.SL_CONFIG exists when assets/config.js\n' +
  ' * resolves its 3-tier priority (window.SL_CONFIG > localStorage > committed default).\n' +
  ' * Git-ignored build artifact: it holds the live URL + PUBLISHABLE key for this deploy.\n' +
  ' * The service-role key never enters this pipeline. Values are JSON-escaped. */\n' +
  'window.SL_CONFIG = { sbUrl: ' + JSON.stringify(sbUrl) +
  ', sbKey: ' + JSON.stringify(sbKey) +
  ', ownerEmails: ' + JSON.stringify(ownerEmails) + ' };\n';

fs.mkdirSync(path.dirname(path.join(ROOT, GENERATED_REL)), { recursive: true });
fs.writeFileSync(path.join(ROOT, GENERATED_REL), generated, 'utf8');
console.log('inject-config: wrote ' + GENERATED_REL + ' (' + sbUrl + ', publishable key, ' + (ownerEmails === '' ? 'no owner emails' : ownerEmails) + ')');

let broken = 0;
for (const name of ENTRY_POINTS) {
  const file = path.join(ROOT, name);
  if (!fs.existsSync(file)) {
    console.error('inject-config: ' + name + ' MISSING - entry point not found at build root');
    broken++;
    continue;
  }
  let html = fs.readFileSync(file, 'utf8');
  if (html.includes('config.generated.js')) {
    console.log(name + ': skipped - tag already present');
    continue;
  }
  const head = /<head(?:\s[^>]*)?>/i.exec(html);
  if (!head) {
    console.error('inject-config: ' + name + ' NO <head> tag - cannot inject');
    broken++;
    continue;
  }
  const at = head.index + head[0].length;
  html = html.slice(0, at) + '\n    ' + TAG + html.slice(at);
  fs.writeFileSync(file, html, 'utf8');
  console.log(name + ': injected - tag placed right after <head>');
}

/* vercel.json lives at the deploy root on Vercel, but the repo keeps its source
   of truth in tools/ so the committed tree stays readable. Copy it across at
   build time; the root copy is a git-ignored artifact (/vercel.json in .gitignore). */
const VERCEL_SRC = path.join(ROOT, 'tools', 'vercel.json');
const VERCEL_DST = path.join(ROOT, 'vercel.json');
if (fs.existsSync(VERCEL_SRC)) {
  try {
    JSON.parse(fs.readFileSync(VERCEL_SRC, 'utf8'));
  } catch (e) {
    fail('tools/vercel.json is not valid JSON: ' + e.message);
  }
  fs.copyFileSync(VERCEL_SRC, VERCEL_DST);
  console.log('inject-config: copied tools/vercel.json -> vercel.json (deploy root)');
} else {
  fail('tools/vercel.json is missing; the deploy would ship without cache/security headers.');
}

if (broken > 0) fail(broken + ' entry point(s) could not be tagged; the deploy would run without config.');

console.log('inject-config: reminder - assets/config.js itself is untouched and keeps its 3-tier priority: window.SL_CONFIG (this build) > localStorage (?sburl/?sbkey dev override) > committed placeholder.');
